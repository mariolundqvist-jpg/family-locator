# Write out the complete mobile/src/i18n/translations.ts
codes = [c for c, n, f in languages_meta]
type_union = " | ".join(f"'{c}'" for c in codes)

out = []
out.append(f"export type SupportedLanguage = {type_union};\n")
out.append("export interface LanguageInfo {\n  code: SupportedLanguage;\n  name: string;\n  flag: string;\n}\n")
out.append("export const LANGUAGES: LanguageInfo[] = [")
for code, name, flag in languages_meta:
    out.append(f"  {{ code: '{code}', name: '{name}', flag: '{flag}' }},")
out.append("];\n")

out.append("export const translations = {")
for code, name, flag in languages_meta:
    d = TRANSLATIONS[code]
    out.append(f"  {code}: {{")
    for k in EN.keys():
        v = d.get(k, EN[k]).replace("\\", "\\\\").replace("'", "\\'")
        out.append(f"    {k}: '{v}',")
    out.append("  },")
out.append("};\n")

with open("mobile/src/i18n/translations.ts", "w", encoding="utf-8") as f:
    f.write("\n".join(out))

print(f"Successfully generated translations for {len(languages_meta)} languages!")
